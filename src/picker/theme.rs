#[derive(Debug, Clone, Default)]
pub struct Theme {
    config: ThemeConfig,
    legacy_accent: Option<String>,
    appearance: Option<ThemeMode>,
}

pub fn config_path(
    override_path: Option<PathBuf>,
    xdg: Option<PathBuf>,
    home: Option<PathBuf>,
) -> PathBuf {
    override_path.unwrap_or_else(|| {
        xdg.map(|dir| dir.join("herdr"))
            .or_else(|| home.map(|dir| dir.join(".config/herdr")))
            .unwrap_or_else(|| env::temp_dir().join("herdr"))
            .join("config.toml")
    })
}

impl Theme {
    pub fn load() -> (Self, Vec<String>) {
        let path = config_path(
            env::var_os("HERDR_CONFIG_PATH").map(PathBuf::from),
            env::var_os("XDG_CONFIG_HOME").map(PathBuf::from),
            env::var_os("HOME").map(PathBuf::from),
        );
        Self::load_path(&path)
    }

    pub fn load_path(path: &Path) -> (Self, Vec<String>) {
        match fs::read_to_string(path) {
            Ok(text) => match Self::parse(&text) {
                Ok(theme) => {
                    let diagnostics = theme.diagnostics();
                    (theme, diagnostics)
                }
                Err(error) => (
                    Self::default(),
                    vec![format!(
                        "read {}: {error:#}; using default theme",
                        path.display()
                    )],
                ),
            },
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                (Self::default(), Vec::new())
            }
            Err(error) => (
                Self::default(),
                vec![format!(
                    "read {}: {error}; using default theme",
                    path.display()
                )],
            ),
        }
    }

    pub fn parse(text: &str) -> Result<Self> {
        let document: toml::Value = toml::from_str(text.strip_prefix('\u{feff}').unwrap_or(text))
            .context("invalid Herdr configuration")?;
        let config: ThemeConfig = document
            .get("theme")
            .cloned()
            .map(toml::Value::try_into)
            .transpose()
            .context("invalid Herdr theme")?
            .unwrap_or_default();
        let legacy_accent = document
            .get("ui")
            .and_then(|ui| ui.get("accent"))
            .and_then(toml::Value::as_str)
            .filter(|accent| *accent != "cyan")
            .filter(|_| {
                config
                    .custom
                    .as_ref()
                    .and_then(|custom| custom.common.accent.as_ref())
                    .is_none()
            })
            .map(str::to_owned);
        Ok(Self {
            config,
            legacy_accent,
            appearance: None,
        })
    }

    pub fn auto_switch(&self) -> bool {
        self.config.auto_switch
    }

    pub fn set_appearance(&mut self, appearance: ThemeMode) {
        self.appearance = Some(appearance);
    }

    pub fn palette(&self) -> Palette {
        let manual = self.config.name.as_deref().unwrap_or("catppuccin");
        let (dark, light) = sibling_names(manual);
        let (name, fallback, overrides) = if self.config.auto_switch {
            if self.appearance == Some(ThemeMode::Light) {
                (
                    self.config.light_name.as_deref().unwrap_or(light),
                    "catppuccin-latte",
                    self.config
                        .custom
                        .as_ref()
                        .and_then(|custom| custom.light.as_ref()),
                )
            } else {
                (
                    self.config.dark_name.as_deref().unwrap_or(dark),
                    "catppuccin",
                    self.config
                        .custom
                        .as_ref()
                        .and_then(|custom| custom.dark.as_ref()),
                )
            }
        } else {
            (manual, "catppuccin", None)
        };
        let mut palette = Palette::from_name(name)
            .unwrap_or_else(|| Palette::from_name(fallback).unwrap_or_else(Palette::catppuccin));
        if let Some(custom) = &self.config.custom {
            palette = palette.with_overrides(&custom.common);
        }
        if let Some(accent) = &self.legacy_accent {
            palette.accent = parse_color(accent);
        }
        if let Some(overrides) = overrides {
            palette = palette.with_overrides(overrides);
        }
        palette
    }

    fn diagnostics(&self) -> Vec<String> {
        let mut diagnostics = Vec::new();
        for (field, name) in [
            ("name", &self.config.name),
            ("dark_name", &self.config.dark_name),
            ("light_name", &self.config.light_name),
        ] {
            if let Some(name) = name
                && canonical_theme_name(name).is_none()
            {
                diagnostics.push(format!(
                    "unknown theme.{field} {name:?}; using Herdr's fallback theme"
                ));
            }
        }
        if let Some(custom) = &self.config.custom {
            for colors in [
                Some(&custom.common),
                custom.light.as_ref(),
                custom.dark.as_ref(),
            ]
            .into_iter()
            .flatten()
            {
                diagnostics.extend(colors.diagnostics());
            }
        }
        if let Some(accent) = &self.legacy_accent
            && let Err(error) = try_parse_color(accent)
        {
            diagnostics.push(error.to_string());
        }
        diagnostics
    }
}

fn sibling_names(name: &str) -> (&str, &str) {
    match canonical_theme_name(name) {
        Some("catppuccin" | "catppuccin-latte") => ("catppuccin", "catppuccin-latte"),
        Some("tokyo-night" | "tokyo-night-day") => ("tokyo-night", "tokyo-night-day"),
        Some("gruvbox" | "gruvbox-light") => ("gruvbox", "gruvbox-light"),
        Some("one-dark" | "one-light") => ("one-dark", "one-light"),
        Some("solarized" | "solarized-light") => ("solarized", "solarized-light"),
        Some("kanagawa" | "kanagawa-lotus") => ("kanagawa", "kanagawa-lotus"),
        Some("rose-pine" | "rose-pine-dawn") => ("rose-pine", "rose-pine-dawn"),
        _ => (name, name),
    }
}

fn parse_color(text: &str) -> Color {
    try_parse_color(text).unwrap_or(Color::Cyan)
}

impl Palette {
    pub fn base_style(self) -> Style {
        Style::default().fg(self.text).bg(self.panel_bg)
    }
    pub fn primary_style(self) -> Style {
        let contrast = if self.panel_bg == Color::Reset {
            self.surface_dim
        } else {
            self.panel_bg
        };
        Style::default()
            .fg(contrast)
            .bg(self.accent)
            .add_modifier(Modifier::BOLD)
    }
    pub fn secondary_style(self) -> Style {
        Style::default()
            .fg(self.text)
            .bg(self.surface0)
            .add_modifier(Modifier::BOLD)
    }
}

